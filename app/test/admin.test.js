
// Admin rules + print branding tests: node test/admin.test.js
const assert = require('assert');
const ADM = require('../core/admin');
const PR = require('../core/print');
let pass = 0; const ok = (c, m) => { assert.ok(c, m); pass++; console.log('  ✓ ' + m); };

console.log('Password strength');
ok(!ADM.checkPassword('abc').ok, 'too short rejected');
ok(!ADM.checkPassword('abcdefgh').ok, 'letters only rejected');
ok(!ADM.checkPassword('12345678').ok, 'digits only rejected');
ok(!ADM.checkPassword('Admin123', { username: 'admin' }).ok, 'password containing the username rejected');
ok(!ADM.checkPassword('password123').ok, 'common password rejected');
ok(!ADM.checkPassword('Kashi@2026', { oldPw: 'Kashi@2026' }).ok, 'same as current password rejected');
ok(!ADM.checkPassword(' Kashi2026').ok, 'leading space rejected');
const good = ADM.checkPassword('Kashi@2026', { username: 'admin', oldPw: 'admin' });
ok(good.ok && good.score >= 3, 'good password accepted, score ' + good.score + ' (' + good.label + ')');
ok(ADM.checkPassword('ganga2027x').ok && ADM.checkPassword('ganga2027x').score < ADM.checkPassword('Ganga#2027-Ghat').score, 'strength score grows with length + variety');

console.log('Username');
ok(ADM.validateUsername('  rssons.owner ', ['admin', 'op1'], 'admin') === 'rssons.owner', 'valid username trimmed + accepted');
assert.throws(() => ADM.validateUsername('OP1', ['admin', 'op1'], 'admin'), /already taken/); ok(true, 'duplicate username (case-insensitive) rejected');
assert.throws(() => ADM.validateUsername('ab', [], 'admin'), /3 to 30/); ok(true, 'too-short username rejected');
assert.throws(() => ADM.validateUsername('ram kumar', [], 'admin'), /no spaces/); ok(true, 'username with space rejected');
assert.throws(() => ADM.validateUsername('admin', ['admin'], 'admin'), /already|taken/); ok(true, 'same username rejected');
ok(ADM.validateUsername('Admin2', ['admin'], 'admin') === 'Admin2', 'changing case-different new name accepted');

console.log('App name & theme');
ok(ADM.cleanAppName(null) === ADM.DEFAULT_APP_NAME && ADM.cleanAppName('   ') === ADM.DEFAULT_APP_NAME, 'blank name = default (reset)');
ok(ADM.cleanAppName('  Kashi   Traders <Accounts> ') === 'Kashi Traders Accounts', 'name cleaned (spaces, < >)');
assert.throws(() => ADM.cleanAppName('x'.repeat(61)), /60/); ok(true, 'name over 60 chars rejected');
ok(ADM.cleanTheme('dark') === 'dark' && ADM.cleanTheme('system') === 'system', 'themes light/dark/system');
assert.throws(() => ADM.cleanTheme('pink')); ok(true, 'unknown theme rejected');
ok(ADM.BUILTIN_ICONS.length >= 4 && ADM.BUILTIN_ICONS.every(b => require('fs').existsSync(require('path').join(__dirname, '..', 'assets', 'icons', b.id + '.png'))), 'every built-in icon file ships in assets/icons');

console.log('Printed documents carry the app name and stay light');
const rep = { title: 'Trial Balance', subtitle: '', columns: [{ k: 'a', label: 'A' }], rows: [{ a: 'x' }], meta: {} };
const S = { name: 'Test Co', address: '', state_code: '09' };
let html = PR.reportHtml(rep, S, {});
ok(/Generated by R&amp;S Sons Accounting/.test(html), 'default footer "Generated by R&S Sons Accounting"');
PR.setAppName('Kashi Traders Accounts'); html = PR.reportHtml(rep, S, {});
ok(/Generated by Kashi Traders Accounts/.test(html) && PR.getAppName() === 'Kashi Traders Accounts', 'renamed app appears in report footer');
PR.setAppName('A <b>bold</b> & name'); html = PR.reportHtml(rep, S, {});
ok(html.includes('Generated by A &lt;b&gt;bold&lt;/b&gt; &amp; name'), 'app name is HTML-escaped in printouts');
ok(/color-scheme:light only/.test(html) && /body\{background:#fff/.test(html), 'printout forces light colours (dark theme never reaches paper/PDF)');
PR.setAppName(null); ok(PR.getAppName() === 'R&S Sons Accounting', 'reset restores default');
console.log(`\nadmin tests: ${pass} passed`);
